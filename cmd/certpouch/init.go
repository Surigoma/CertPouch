func runInit(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 || (args[0] != "client" && args[0] != "server") {
		fmt.Fprintln(stderr, "Usage: certpouch init server|client --help")
		if len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
			return 0
		}
		return 2
	}
	role := args[0]
	flags := flag.NewFlagSet("init "+role, flag.ContinueOnError)
	flags.SetOutput(stderr)
	out := flags.String("out", "", "absolute path to a new configuration directory")
	id := flags.String("id", "", "client ID used on both hosts")
	name := flags.String("name", "", "certificate name used on both hosts and in the DNS inventory")
	san := flags.String("dns-san", "", "expected certificate DNS SAN (defaults to --name)")
	trust := flags.String("trust-ca", "", "absolute path to the CA bundle for the distributed certificate")
	issuer := flags.String("issuer", "", "absolute path to the issuing CA certificate")
	var generate func(string) (string, error)
	var required []*string
	if role == "client" {
		origin := flags.String("url", "", "HTTPS origin of the distribution server")
		serverCA := flags.String("server-ca", "", "absolute path to the distribution server's TLS CA bundle")
		unit := flags.String("unit", "", "systemd unit that uses the distributed certificate")
		action := flags.String("action", "restart", "systemd operation: restart or reload")
		required = []*string{origin, serverCA, unit}
		generate = func(dir string) (string, error) {
			return initClient(dir, *id, *name, *san, *trust, *issuer, *origin, *serverCA, *unit, *action)
		}
	} else {
		listen := flags.String("listen", "127.0.0.1:8443", "HTTPS listen address")
		cert := flags.String("tls-cert", "", "absolute path to the distribution server's TLS certificate")
		key := flags.String("tls-key", "", "absolute path to the distribution server's TLS private key")
		hash := flags.String("token-hash", "", "path to the client.token.sha256 generated by init client")
		cache := flags.String("cache", "", "absolute path to a Sheets JSON cache")
		csv := flags.String("csv", "", "absolute path to a Sheets CSV export")
		zone := flags.String("zone", "", "DNS inventory zone")
		prefix := flags.String("fallback-prefix", "", "IPv4 prefix used before one is specified in the inventory")
		required = []*string{cert, key, hash, zone, prefix}
		generate = func(dir string) (string, error) {
			if (*csv == "") == (*cache == "") {
				return "", fmt.Errorf("specify exactly one of --cache and --csv")
			}
			return initServer(dir, *id, *name, *san, *trust, *issuer, *listen, *cert, *key, *hash, *cache, *csv, *zone, *prefix)
		}
	}
	if err := flags.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}
	if flags.NArg() != 0 || !filepath.IsAbs(*out) || !storage.ValidPublicationName(*id) || !storage.ValidPublicationName(*name) ||
		!filepath.IsAbs(*trust) || !filepath.IsAbs(*issuer) {
		flags.Usage()
		return 2
	}
	for _, value := range required {
		if *value == "" {
			flags.Usage()
			return 2
		}
	}
	if *san == "" {
		*san = *name
	}
	path, err := generate(filepath.Clean(*out))
	if err == nil {
		_, err = fmt.Fprintln(stdout, path)
	}
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	return 0
}

func initClient(dir, id, name, san, trust, issuer, origin, serverCA, unit, action string) (string, error) {
	destination := filepath.Join(dir, "deployment")
	if _, _, err := deployment.Configure(destination, "", "", "", "", unit, action); err != nil {
		return "", err
	}
	var secret [32]byte
	if _, err := rand.Read(secret[:]); err != nil {
		return "", fmt.Errorf("generate client token: %w", err)
	}
	token := base64.RawURLEncoding.EncodeToString(secret[:])
	hash := sha256.Sum256([]byte(token))
	body := fmt.Sprintf(`server:
  url: %q
  ca_file: %q
client:
  id: %q
  token_file: %q
validation:
  trust_ca_file: %q
certificates:
  - name: %q
    destination: %q
    expected_dns_sans: [%q]
    issuer_certificate: %q
    service:
      unit: %q
      action: %q
`, origin, serverCA, id, filepath.Join(dir, "client.token"), trust, name, destination, san, issuer, unit, action)
	return writeInit(dir, "client.yaml", "deployment", body, map[string]string{
		"client.token": token + "\n", "client.token.sha256": fmt.Sprintf("%x\n", hash),
	}, func(path string) error {
		cfg, err := config.LoadClient(path)
		if err != nil {
			return err
		}
		_, err = client.New(cfg.URL, cfg.ID, cfg.Token, cfg.TLSRoots)
		return err
	})
}

func initServer(dir, id, name, san, trust, issuer, listen, cert, key, hashPath, cache, csv, zone, prefix string) (string, error) {
	info, err := os.Stat(hashPath)
	if err != nil {
		return "", fmt.Errorf("inspect client token hash: %w", err)
	}
	if !info.Mode().IsRegular() || info.Size() > 66 {
		return "", fmt.Errorf("client token hash must be a regular file containing a lowercase SHA-256 hash")
	}
	hashFile, err := os.Open(hashPath)
	if err != nil {
		return "", fmt.Errorf("open client token hash: %w", err)
	}
	defer hashFile.Close()
	hash, err := io.ReadAll(io.LimitReader(hashFile, 67))
	if err != nil {
		return "", fmt.Errorf("read client token hash: %w", err)
	}
	value := strings.TrimSuffix(strings.TrimSuffix(string(hash), "\n"), "\r")
	decoded, err := hex.DecodeString(value)
	if err != nil || len(decoded) != sha256.Size || value != strings.ToLower(value) {
		return "", fmt.Errorf("expected a lowercase SHA-256 client token hash")
	}
	inventory := fmt.Sprintf("cache_file: %q", cache)
	if csv != "" {
		inventory = fmt.Sprintf("csv_files: [%q]", csv)
	}
	body := fmt.Sprintf(`server:
  listen: %q
  publication_refresh: "1m"
  inventory_refresh: "1m"
  tls:
    certificate: %q
    private_key: %q
storage:
  certificate_dir: %q
  trust_ca_file: %q
dns_inventory:
  %s
  zone: %q
  fallback_prefix: %q
certificates:
  - name: %q
    expected_dns_sans: [%q]
    issuer_certificate: %q
clients:
  - id: %q
    enabled: true
    token_hash_file: %q
`, listen, cert, key, filepath.Join(dir, "publications"), trust, inventory, zone, prefix, name, san, issuer, id, filepath.Join(dir, "client.token.sha256"))
	return writeInit(dir, "server.yaml", "publications", body, map[string]string{
		"client.token.sha256": value + "\n",
	}, func(path string) error {
		cfg, err := config.LoadServer(path)
		if err != nil {
			return err
		}
		if len(cfg.Clients[0].CertificateIPs[name]) == 0 {
			return fmt.Errorf("the certificate name has no address in the DNS inventory")
		}
		_, err = tls.LoadX509KeyPair(cfg.TLSCertificate, cfg.TLSPrivateKey)
		return err
	})
}

func writeInit(dir, configFile, dataDir, body string, files map[string]string, validate func(string) error) (path string, err error) {
	if err := os.Mkdir(dir, 0700); err != nil {
		return "", fmt.Errorf("create new init directory: %w", err)
	}
	files[configFile] = body
	var created []string
	defer func() {
		if err != nil {
			for _, child := range created {
				err = errors.Join(err, os.Remove(child))
			}
			err = errors.Join(err, os.Remove(dir))
		}
	}()
	data := filepath.Join(dir, dataDir)
	if err := os.Mkdir(data, 0700); err != nil {
		return "", err
	}
	created = append(created, data)
	for name, contents := range files {
		child := filepath.Join(dir, name)
		file, err := os.OpenFile(child, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
		if err != nil {
			return "", err
		}
		created = append(created, child)
		_, err = io.WriteString(file, contents)
		if err := errors.Join(err, file.Close()); err != nil {
			return "", err
		}
	}
	path = filepath.Join(dir, configFile)
	if err := validate(path); err != nil {
		return "", fmt.Errorf("validate generated config: %w", err)
	}
	return path, nil
}
